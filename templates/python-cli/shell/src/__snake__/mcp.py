"""MCP server on stdio (JSON-RPC 2.0, one message per line), dual-era: 2026-07-28 clients discover it and send
the protocol version with every request; older clients use the initialize handshake. Every command is a tool.
Generated by anything-anything from anything.toml."""

from __future__ import annotations

import json
import sys
from typing import Any

from . import __version__
from .cli import MANIFEST, args_from, run_command

SUPPORTED = ["2026-07-28", "2025-11-25", "2025-06-18", "2025-03-26"]
VERSION_KEY = "io.modelcontextprotocol/protocolVersion"


def _info() -> dict[str, str]:
    return {"name": MANIFEST["name"], "version": __version__}


def _error(id_: Any, code: int, message: str, data: Any = None) -> dict[str, Any]:
    error: dict[str, Any] = {"code": code, "message": message}
    if data is not None:
        error["data"] = data
    return {"jsonrpc": "2.0", "id": id_, "error": error}


def _call(name: str, arguments: dict[str, Any]) -> dict[str, Any] | None:
    command = next((c for c in MANIFEST["commands"] if c["tool"] == name), None)
    if command is None:
        return None
    try:
        out = run_command(command["name"], args_from(command, arguments or {}))
    except Exception as e:
        return {"resultType": "complete", "content": [{"type": "text", "text": str(e)}], "isError": True}
    text = out.text or json.dumps(out.data, indent=2, ensure_ascii=False)
    result: dict[str, Any] = {"resultType": "complete", "content": [{"type": "text", "text": text}], "isError": False}
    if out.data is not None:
        result["structuredContent"] = out.data
    return result


def handle(msg: dict[str, Any]) -> dict[str, Any] | None:
    if "id" not in msg:
        return None
    id_ = msg["id"]
    params = msg.get("params") or {}
    version = (params.get("_meta") or {}).get(VERSION_KEY)
    if version is not None and version not in SUPPORTED:
        return _error(id_, -32022, "Unsupported protocol version", {"supported": SUPPORTED, "requested": version})
    method = msg.get("method")
    if method == "server/discover":
        result: dict[str, Any] = {
            "resultType": "complete",
            "supportedVersions": SUPPORTED,
            "capabilities": {"tools": {}},
            "instructions": MANIFEST["instructions"],
            "ttlMs": 3_600_000,
            "cacheScope": "public",
            "_meta": {"io.modelcontextprotocol/serverInfo": _info()},
        }
    elif method == "initialize":
        asked = params.get("protocolVersion", "2025-11-25")
        result = {
            "protocolVersion": asked if asked in SUPPORTED else "2025-11-25",
            "capabilities": {"tools": {}},
            "serverInfo": _info(),
            "instructions": MANIFEST["instructions"],
        }
    elif method == "ping":
        result = {}
    elif method == "tools/list":
        result = {"resultType": "complete", "tools": MANIFEST["tools"], "ttlMs": 300_000, "cacheScope": "public"}
    elif method == "tools/call":
        called = _call(params.get("name", ""), params.get("arguments") or {})
        if called is None:
            return _error(id_, -32602, f"unknown tool {params.get('name')}")
        result = called
    else:
        return _error(id_, -32601, f"unknown method {method}")
    return {"jsonrpc": "2.0", "id": id_, "result": result}


def serve() -> int:
    for line in sys.stdin:
        if not line.strip():
            continue
        try:
            reply = handle(json.loads(line))
        except json.JSONDecodeError as e:
            reply = _error(None, -32700, str(e))
        if reply is not None:
            sys.stdout.write(json.dumps(reply, ensure_ascii=False) + "\n")
            sys.stdout.flush()
    return 0
